-- Один индекс, который снимает нагрузку с диска.
--
-- Симптом: отправка одного короткого сообщения поднимала на сервере около
-- ста мегабайт чтения на десяток секунд.
--
-- Причина. На messages сейчас стоят PRIMARY (id), idx_sender (sender_id),
-- idx_receiver (receiver_id) и idx_conv (sender_id, receiver_id). Индекс по
-- получателю есть — и всё равно больно, потому что запрос
--
--     WHERE receiver_id = ? AND is_read = 0 [AND sender_id = ?]
--
-- находит по idx_receiver все входящие письма, но ни is_read, ни sender_id в
-- этом индексе нет: за каждым найденным письмом сервер идёт в саму таблицу.
-- А строка там широкая — longtext с текстом и четыре longblob. Вот эти походы
-- и дают полку чтения.
--
-- Уходит такой запрос:
--   * на каждый опрос списка чатов (2,5 с) у КАЖДОГО открытого клиента;
--   * принудительно на каждое событие «новое сообщение» — поэтому полка и
--     совпадает с отправкой;
--   * на каждую отметку «прочитано»;
--   * дважды на каждый показ списка диалогов.
--
-- Индекс ниже закрывает такой запрос целиком: ответ собирается из самого
-- индекса, ходить в таблицу незачем.
--
-- Больше ничего добавлять не нужно. Направление «я писал» ложится на idx_conv;
-- (sender_id, receiver_id, id) — это он и есть, потому что в InnoDB первичный
-- ключ дописывается в конец любого вторичного индекса. У group_messages и
-- server_messages есть idx_group (group_id) и idx_ch (channel_id), а MAX(id)
-- по ним — движение к концу индекса.
--
-- Ошибка 1061 (Duplicate key name) = индекс уже стоит, всё в порядке.
-- На MySQL 5.6+ это операция «на месте»: запись в таблицу не блокируется.

ALTER TABLE `messages`
  ADD INDEX `idx_msg_recv_read` (`receiver_id`, `is_read`, `sender_id`);


