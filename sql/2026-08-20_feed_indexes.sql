-- Один индекс, который снимает нагрузку с диска.
--
-- Симптом: отправка одного короткого сообщения поднимала на сервере около
-- ста мегабайт чтения на десяток секунд.
--
-- Причина: в messages есть только idx_msg_pair (sender_id, receiver_id) и
-- idx_msg_created (created_at). Всё, что спрашивается ОТ ПОЛУЧАТЕЛЯ, на них
-- опереться не может и сканирует таблицу целиком — а строки там широкие,
-- вложения лежат в этой же таблице:
--
--   * непрочитанные по отправителям — WHERE receiver_id=? AND is_read=0
--   * отметка «прочитано»           — ... AND is_read=0
--   * список диалогов, ветка «мне писали»
--
-- Первый из них уходит на КАЖДЫЙ тик опроса у КАЖДОГО клиента и вдобавок
-- принудительно на каждое событие «новое сообщение» — поэтому полка чтения
-- и совпадала с отправкой.
--
-- Больше ничего добавлять не нужно. Направление «я писал» ложится на
-- существующий idx_msg_pair; (sender_id, receiver_id, id) в InnoDB — это и
-- есть idx_msg_pair, потому что первичный ключ дописывается в конец любого
-- вторичного индекса. У group_messages и server_messages нужные индексы
-- (group_id) и (channel_id) уже есть с самого начала.
--
-- Ошибка 1061 (Duplicate key name) = индекс уже стоит, всё в порядке.
-- Приложение тоже пробует создать его само (DbMigrator, миграция 17), но
-- учётной записи приложения обычно не хватает права ALTER.

ALTER TABLE `messages`
  ADD INDEX `idx_msg_recv_read` (`receiver_id`, `is_read`, `sender_id`);
