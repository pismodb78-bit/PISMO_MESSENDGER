-- =====================================================================
-- PISMO — миграция 15: server_mentions (упоминания в каналах серверов)
-- Дата: 2026-08-16
--
-- Зачем: красная цифра упоминаний на сервере не работала НИКОГДА. Она
-- считалась запросом вида
--     LOWER(sm.text) LIKE CONCAT('%@', login, '%')
-- по server_messages.text, а текст лежит в БД ЗАШИФРОВАННЫМ (Crypto.Enc —
-- AES-GCM, результат в Base64). В алфавите Base64 нет даже символа «@»,
-- поэтому условие не выполнялось ни при каком сообщении.
--
-- Теперь адресаты «@…» вычисляются ОДИН РАЗ при отправке, пока открытый
-- текст на руках, и складываются в эту таблицу. Бейдж после этого —
-- обычный COUNT по индексу: от шифрования не зависит и одинаково работает
-- на ПК и в мобильной версии.
--
-- Запуск: phpMyAdmin → выбрать базу PISMO слева → вкладка SQL → вставить →
--         «Вперёд». Под пользователем с правами на CREATE (root).
-- =====================================================================


-- ── ШАГ 1 (обязательный) ─────────────────────────────────────────────
-- message_id — BIGINT: id сообщений берётся из AUTO_INCREMENT и со
-- временем может выйти за пределы INT.
-- Первичный ключ (message_id, user_id) заодно защищает от дублей при
-- повторной записи, а idx_mention_lookup обслуживает выборку бейджей.

CREATE TABLE IF NOT EXISTS server_mentions (
    message_id BIGINT NOT NULL,
    channel_id INT    NOT NULL,
    user_id    INT    NOT NULL,
    PRIMARY KEY (message_id, user_id),
    KEY idx_mention_lookup (user_id, channel_id, message_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;


-- ── ШАГ 2 (обязательный) ─────────────────────────────────────────────
-- Отметить миграцию применённой, чтобы приложение не пыталось повторять её
-- при каждом запуске.

INSERT IGNORE INTO schema_migrations (id, name)
VALUES (15, 'server_mentions: упоминания в каналах (текст в БД зашифрован)');


-- ── ШАГ 3 (проверка) ─────────────────────────────────────────────────
-- Должен отработать без ошибки и вернуть пустой результат (0 строк) —
-- таблица создана и пока пуста. Через information_schema проверять нельзя:
-- на этом хостинге доступ к нему закрыт даже администратору.

SELECT * FROM server_mentions LIMIT 5;


