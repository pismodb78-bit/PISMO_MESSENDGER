--
--  ЗАЧЕМ ОТДЕЛЬНЫМ ФАЙЛОМ. Обычно схему правят сами приложения при запуске, но
--  у учётной записи приложения на этом хостинге нет прав ALTER — значит, эти
--  две колонки кладёт администратор.
--
--  Пока их нет, окно «Настройки сервера» выглядит рабочим, но цвет и картинка
--  не сохраняются: запрос падает на неизвестной колонке.
--
--      mysql -u root -p --force bdauth < 2026-10-11_servers_avatar.sql
--
--  Запускать можно сколько угодно раз: MariaDB понимает IF NOT EXISTS у
--  ALTER TABLE, повторный запуск ничего не сломает.
--
--  То же самое есть в pismo-all.sql — этот файл для тех, кому нужно только
--  это изменение, без прогона всего остального.
-- ============================================================================

USE bdauth;

-- Картинка лежит в самой таблице, как аватары пользователей: отдельного
-- хранилища у проекта нет. В списке серверов её не читают — там нужен только
-- факт наличия, — поэтому вес колонки на выдачу списка не влияет.
ALTER TABLE servers ADD COLUMN IF NOT EXISTS avatar_data  LONGBLOB    NULL;

-- Цвет нужен и без картинки: буквенный значок перестаёт быть одинаковым у
-- всех серверов. Хранится как «#RRGGBB».
ALTER TABLE servers ADD COLUMN IF NOT EXISTS avatar_color VARCHAR(16) NULL;

-- Отметка в журнале: приложения не станут повторять то, что уже сделано.
INSERT IGNORE INTO schema_migrations (id, name) VALUES
  (24, 'servers: аватар и цвет — кастомизация серверов');

-- Проверка: должны появиться обе колонки и строка 24 в журнале.
SHOW COLUMNS FROM servers LIKE 'avatar%';
SELECT id, name, applied_at FROM schema_migrations WHERE id = 24;
