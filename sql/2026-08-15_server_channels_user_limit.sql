-- =====================================================================
-- PISMO — миграция 14: server_channels.user_limit
--                      (вместимость голосового канала)
-- Дата: 2026-08-15
--
-- Зачем: 0 = без ограничения, иначе столько человек максимум может быть
-- в голосовом канале одновременно. Приложение показывает пилюлю
-- «занято/лимит» в списке каналов и не пускает в заполненный канал.
--
-- Почему вручную: учётной записи, под которой в БД ходит клиент, не
-- выданы права на ALTER — DbMigrator (пункт 14) тихо пропускает миграцию.
--
-- ВАЖНО про этот хостинг: доступ к information_schema закрыт даже
-- администратору (#1044), поэтому проверки «есть ли уже колонка» здесь
-- НЕТ — она была бы через information_schema. Скрипт просто выполняет
-- ALTER. Если колонка уже добавлена, MySQL ответит
--     #1060 - Duplicate column name 'user_limit'
-- — это НЕ поломка, а «уже сделано», такую ошибку можно игнорировать.
--
-- Запуск: phpMyAdmin → выбрать базу PISMO слева → вкладка SQL →
--         вставить → «Вперёд». Шаги выполнять ПО ОДНОМУ: phpMyAdmin
--         останавливается на первой же ошибке и не идёт дальше.
-- =====================================================================


-- ── ШАГ 1 (обязательный) ─────────────────────────────────────────────
-- Собственно вместимость канала. Значение по умолчанию 0 означает
-- «без ограничения», поэтому все существующие каналы продолжают
-- работать ровно как раньше.

ALTER TABLE server_channels ADD COLUMN user_limit INT NOT NULL DEFAULT 0;


-- ── ШАГ 2 (обязательный) ─────────────────────────────────────────────
-- Отметить миграцию применённой, чтобы приложение не пыталось повторять
-- её при каждом запуске.

INSERT IGNORE INTO schema_migrations (id, name)
VALUES (14, 'server_channels.user_limit: вместимость голосового канала');


-- ── ШАГ 3 (проверка) ─────────────────────────────────────────────────
-- Должен отработать без ошибки и показать колонку user_limit со
-- значением 0 у всех каналов. Через information_schema проверить нельзя
-- (доступ закрыт), поэтому проверяем прямым запросом самой колонки.

SELECT id, name, type, user_limit
FROM server_channels
ORDER BY id
LIMIT 20;


