-- Закреплённые ЧАТЫ, общие для ПК и телефона (миграция 19).
--
-- Раньше каждый клиент хранил список закреплённых диалогов у себя: на ПК
-- файлом pinned_chats_<id>.txt, на телефоне — в настройках приложения. Из-за
-- этого один и тот же человек видел РАЗНЫЙ порядок списка на компьютере и в
-- телефоне. Теперь закрепы живут здесь и у аккаунта они одни.
--
-- Приложения создают таблицу сами (DbMigrator, миграция 19). Этот файл нужен
-- только если у учётной записи приложения нет права CREATE — тогда таблицу
-- кладёт администратор, и миграция отметится выполненной при следующем запуске.
--
-- scope оставлен на будущее с теми же значениями, что у закреплённых
-- сообщений: 0 — личный чат, 1 — групповой. Сейчас пишется только 0.

CREATE TABLE IF NOT EXISTS chat_pins (
  user_id   INT       NOT NULL,
  scope     TINYINT   NOT NULL DEFAULT 0,
  target_id INT       NOT NULL,
  pinned_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (user_id, scope, target_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
