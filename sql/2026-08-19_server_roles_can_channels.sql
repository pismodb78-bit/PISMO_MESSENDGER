-- Отдельное право роли: управление каналами (создание, переименование,
-- удаление, лимит участников) — без доступа к настройкам ролей и сервера.
--
-- Выполнять под пользователем, которому разрешён ALTER (приложение DDL не делает).
-- Скрипт безопасно запускать повторно: при уже существующей колонке MySQL
-- вернёт ошибку 1060 (Duplicate column name) — это значит «уже применено».

ALTER TABLE `server_roles`
  ADD COLUMN `can_channels` TINYINT(1) NOT NULL DEFAULT 0;

-- Разовый перенос: роли, у которых уже было общее управление, получают и
-- каналы — чтобы после обновления никто не потерял доступ. Дальше права
-- независимы: снятая галочка «Каналы» отбирает их даже у управляющего
-- сервером. Владелец сервера может всё всегда, права ролей его не касаются.
UPDATE `server_roles` SET `can_channels` = 1 WHERE `can_manage` = 1;
