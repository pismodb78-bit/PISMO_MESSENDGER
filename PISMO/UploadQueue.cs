using System;
using System.Threading.Tasks;

namespace PISMO
{
    /// <summary>
    /// Очередь отправок вложений: одна за другой, а не все разом.
    ///
    /// ЗАЧЕМ. Пока отправка держала модальное окно, файлы уходили строго по
    /// одному — цикл по вложениям стоял на каждом. Окна больше нет, и три
    /// выбранных файла ринулись бы в базу разом, тремя соединениями, каждое со
    /// своим блобом. На телефоне это уже проходили: половина передач падала с
    /// потерей связи.
    ///
    /// Очередь ОБЩАЯ для личных сообщений, групп и каналов серверов. Канал и
    /// личный чат живут в разных окнах, но соединения и канал связи у них
    /// одни — две многомегабайтные заливки наперегонки мешали бы друг другу
    /// ровно так же.
    /// </summary>
    internal static class UploadQueue
    {
        private static readonly object Lock = new();
        private static Task _chain = Task.CompletedTask;

        public static void Enqueue(Action body)
        {
            if (body == null) return;
            lock (Lock)
            {
                _chain = _chain.ContinueWith(_ =>
                {
                    // Своя ошибка не должна обрывать всю цепочку: следующий
                    // файл к предыдущему отношения не имеет.
                    try { body(); } catch { }
                }, TaskScheduler.Default);
            }
        }
    }
}
