        // ── «Часто используемые» (локально, как у Win+.) ──────────────────
        private static readonly object _lock = new();
        private static List<string> _recent;

        private static string RecentPath => Path.Combine(
            Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData),
            "PISMO", "recent_emoji.txt");

        public static List<string> Recent()
        {
            lock (_lock)
            {
                if (_recent != null) return _recent;
                var list = new List<string>();
                try
                {
                    if (File.Exists(RecentPath))
                        list = File.ReadAllLines(RecentPath)
                            .Select(l => l.Trim()).Where(l => l.Length > 0).Distinct().Take(40).ToList();
                }
                catch { }
                if (list.Count == 0)
                    list = new List<string> { "👍", "❤️", "😂", "😮", "😢", "🔥", "🎉", "👀" };
                _recent = list;
                return _recent;
            }
        }

        public static void AddRecent(string emoji)
        {
            if (string.IsNullOrWhiteSpace(emoji)) return;
            lock (_lock)
            {
                var list = Recent();
                list.Remove(emoji);
                list.Insert(0, emoji);
                if (list.Count > 40) list.RemoveRange(40, list.Count - 40);
                try
                {
                    Directory.CreateDirectory(Path.GetDirectoryName(RecentPath)!);
                    File.WriteAllLines(RecentPath, list);
                }
                catch { }
            }
        }
